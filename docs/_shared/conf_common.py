# The book's home on GitHub. Used when nothing else names the repository
# (e.g. a local checkout without an ``origin`` remote), so the GitHub icon
# in the top bar is always shown.
DEFAULT_REPO_URL = "https://github.com/betterweizh/lecture-notes-operation-research"


def _detect_repo_url() -> str:
    """Return the https URL of the repository.

    Order: ``DOCS_REPO_URL``, then ``GITHUB_REPOSITORY`` (set in GitHub
    Actions), then the ``origin`` remote of the local checkout, then
    ``DEFAULT_REPO_URL``.
    """
    url = _os.environ.get("DOCS_REPO_URL", "").strip()
    if url:
        return url.rstrip("/")
    slug = _os.environ.get("GITHUB_REPOSITORY", "").strip()
    if slug:
        server = _os.environ.get("GITHUB_SERVER_URL", "https://github.com")
        return f"{server.rstrip('/')}/{slug}"
    try:
        # Bytes, decoded as UTF-8 below: git's messages may contain a
        # non-ASCII path that the Windows locale encoding cannot decode.
        result = _subprocess.run(
            ["git", "-C", str(_ROOT), "remote", "get-url", "origin"],
            stdout=_subprocess.PIPE,
            stderr=_subprocess.DEVNULL,
            timeout=5,
            check=False,
        )
    except (OSError, _subprocess.SubprocessError):
        return DEFAULT_REPO_URL
    remote = result.stdout.decode("utf-8", "replace").strip()
    # git@github.com:owner/repo.git -> https://github.com/owner/repo
    match = _re.match(r"^[^@/:]+@([^:/]+):(.+?)(?:\.git)?/?$", remote)
    if match:
        return f"https://{match.group(1)}/{match.group(2)}"
    # ssh://git@github.com:22/owner/repo.git -> https://github.com/owner/repo
    match = _re.match(
        r"^(?:git\+)?ssh://(?:[^@/]+@)?([^:/]+)(?::\d+)?/(.+?)(?:\.git)?/?$",
        remote,
    )
    if match:
        return f"https://{match.group(1)}/{match.group(2)}"
    match = _re.match(r"^(https?://.+?)(?:\.git)?/?$", remote)
    if match:
        # Drop credentials such as https://user:token@host/... (everything
        # up to the last "@" before the path).
        return _re.sub(r"^(https?://)[^/]*@", r"\1", match.group(1))
    return DEFAULT_REPO_URL


REPO_URL = _detect_repo_url()

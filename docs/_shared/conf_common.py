def apply_language(lang: str, ns: dict) -> None:
    """Apply the settings of one edition to a ``conf.py`` namespace.

    Call it last in ``docs/<lang>/conf.py`` as
    ``apply_language("<lang>", globals())``. It sets ``language``,
    ``lang_switch_current``, ``lang_switch_languages``, ``toc_title``,
    ``path_to_docs`` (``docs/<lang>``) and ``numfig_format``, appends the
    ``lang-switch.js`` and ``open-dropdown.js`` script tags to
    ``html_js_files`` (other entries are kept), and copies ``toc_title`` and
    ``path_to_docs`` into the book theme's options (other options are kept).

    Parameters
    ----------
    lang : str
        Edition code, a key of ``LANGUAGES`` (``"en"`` or ``"zh"``).
    ns : dict
        The ``globals()`` of the calling ``conf.py``.
    """
    if lang not in LANGUAGES:
        raise ValueError(
            f"unknown edition {lang!r}; add it to LANGUAGES in docs/_shared/conf_common.py"
        )
    info = LANGUAGES[lang]
    ns["language"] = info["sphinx"]
    ns["lang_switch_current"] = lang
    ns["lang_switch_languages"] = LANGUAGES
    ns["toc_title"] = info["toc_title"]
    ns["path_to_docs"] = f"docs/{lang}"
    ns["numfig_format"] = dict(NUMFIG_FORMATS.get(lang, NUMFIG_FORMATS["en"]))
    scripts = [
        (
            "lang-switch.js",
            {
                "data-storage-key": LANG_STORAGE_KEY,
                "data-current-lang": lang,
                "defer": "defer",
            },
        ),
        ("open-dropdown.js", {"defer": "defer"}),
    ]
    # Keep scripts that the conf.py added itself; replace only ours.
    ours = {name for name, _attrs in scripts}
    kept = [
        js
        for js in ns.get("html_js_files", [])
        if (js[0] if isinstance(js, (tuple, list)) else js) not in ours
    ]
    ns["html_js_files"] = kept + scripts
    if ns.get("html_theme") == "sphinx_book_theme":
        options = dict(ns.get("html_theme_options", {}))
        options["toc_title"] = info["toc_title"]
        options["path_to_docs"] = f"docs/{lang}"
        ns["html_theme_options"] = options
